#!/usr/bin/env python3
"""mkcost.py <dc_cost.inc> <dc.log>...: the master-cycle cost table the
decompiled routines charge (dc_rt.c dc_leave).

Measure with the original code standing in for every decompiled entry:
  tools/decomp/run.sh <scenario> <out> CT_DECOMP_ORIGINAL=1   (CHECK=0)
Each run's dc.log ends with "C pc24 calls total-master-cycles" lines (check
mode writes the same lines for its reference runs). The table holds the mean
per call over all logs. A decompiled entry no log measured gets an estimate:
its static instruction count (fdis, without callees) times the median
cycles-per-instruction of the measured ones, or that median cost for code
outside the ROM (7E); those are marked "estimate" and listed on stderr.
Entries in cost_self_timed.txt (they poll the hardware with dc_spend) get 0."""
import sys, os, re, glob, collections, statistics
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
from fdis import walk
import routines
root = os.path.dirname(os.path.dirname(here))
rom = open(f'{root}/ct.sfc', 'rb').read()

tot = collections.Counter(); n = collections.Counter()
for path in sys.argv[2:]:
    for l in open(path, errors='replace'):
        if l.startswith('C '):
            _, pc, k, c = l.split()
            n[int(pc, 16)] += int(k); tot[int(pc, 16)] += int(c)

entries = set()
for f in glob.glob(f'{root}/src/decomp/*.c'):
    entries |= {int(p, 16) for p in re.findall(r'DC_ENTRY\(([0-9A-F]{6}),', open(f).read())}

modes = collections.defaultdict(list)
for pc, m, x, d in routines.load(): modes[pc].append((m, x))
def ninstr(pc):
    if (pc >> 16) < 0xC0: return None
    m, x = (modes.get(pc) or [(1, 1)])[0]
    try: return len(walk(rom, pc, m, x)[0])
    except Exception: return None

self_timed = {int(l.split()[0], 16) for l in open(f'{here}/cost_self_timed.txt') if l.strip() and not l.startswith('#')}
cost = {pc: round(tot[pc] / n[pc]) for pc in entries if n[pc]}
ratio = [cost[pc] / k for pc in cost if pc not in self_timed for k in [ninstr(pc)] if k]
cpi = statistics.median(ratio) if ratio else 40
med = round(statistics.median(v for pc, v in cost.items() if pc not in self_timed)) if cost else 1000
est = {}
for pc in sorted(entries - set(cost) - self_timed):
    k = ninstr(pc)
    est[pc] = round(cpi * k) if k else med

with open(sys.argv[1], 'w') as out:
    out.write('/* generated by tools/decomp/mkcost.py: { pc24, master cycles per call },\n'
              f' * mean over {len(sys.argv) - 2} measurement logs; estimates: {cpi:.1f} x static instructions */\n')
    for pc in sorted(entries):
        if pc in self_timed: out.write(f'{{ 0x{pc:06X}, 0 }},   /* self-timed (cost_self_timed.txt) */\n')
        elif pc in cost: out.write(f'{{ 0x{pc:06X}, {cost[pc]} }},   /* {n[pc]} calls */\n')
        else: out.write(f'{{ 0x{pc:06X}, {est[pc]} }},   /* estimate */\n')
print(f'{len(cost)} measured, {len(est)} estimated (cpi {cpi:.1f}, median {med})', file=sys.stderr)
print('estimated: ' + ' '.join(f'{pc:06X}' for pc in sorted(est)), file=sys.stderr)
